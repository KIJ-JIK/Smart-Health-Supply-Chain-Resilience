L("import { PoolClient } from 'pg';")
L("import { eventBus } from '../src/events/eventBus';")
L("")
L("// --------------- In-memory DB state ---------------")
L("interface Batch { id: string; phc_id: string; medicine_id: string; remaining_qty: number; expiry_date: string; minimum_threshold: number; }")
L("interface BillingTxn { id: string; phc_id: string; client_txn_id: string; patient_ref: string|null; dispensed_by_staff_id: string|null; total_amount: number; client_timestamp: string; status: string; }")
L("interface DispensedItem { id: string; billing_transaction_id: string; batch_id: string; medicine_id: string; quantity: number; unit_price: number; }")
L("interface ConsumptionRow { medicine_id: string; qty_dispensed: number; }")
L("")
L("let batches: Batch[] = [];")
L("let billingTxns: BillingTxn[] = [];")
L("let dispensedItems: DispensedItem[] = [];")
L("let consumptionRows: ConsumptionRow[] = [];")
L("let nextId = 1;")
L("function uid() { return String(nextId++); }")
L("")
L("function resetState() {")
L("  batches = []; billingTxns = []; dispensedItems = []; consumptionRows = []; nextId = 1;")
L("  eventBus.clearHistory();")
