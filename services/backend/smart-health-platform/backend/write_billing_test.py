L("/**")
L(" * test_billing_fefo.ts -- Integration tests for Prompt 9: FEFO Billing / Dispensing Engine")
L(" *")
L(" * Scenarios:")
L(" *  1. Happy-path checkout: single medicine, single batch, FEFO order honoured")
L(" *  2. Cross-batch deduction: qty spans two batches, earliest-expiry drained first")
