L("// --------------- Mock PoolClient ---------------")
L("type QueryFn = (sql: string, params?: any[]) => Promise<{ rows: Record<string,any>[] }>;")
L("")
L("function makeMockClient(): PoolClient {")
L("  const handler: QueryFn = async (sql: string, params: any[] = []) => {")
L("    const s = sql.replace(/\\s+/g, ' ').trim();")
L("")
L("    // Idempotency SELECT on billing_transactions by client_txn_id")
L("    if (s.includes('FROM billing_transactions') && s.includes('client_txn_id')) {")
L("      const found = billingTxns.find((t) => t.phc_id === params[0] && t.client_txn_id === params[1]);")
L("      return { rows: found ? [{ id: found.id, total_amount: found.total_amount }] : [] };")
L("    }")
L("    // Re-fetch dispensed_items for idempotency reply")
L("    if (s.includes('FROM dispensed_items') && s.includes('billing_transaction_id')) {")
L("      const rows = dispensedItems.filter((d) => d.billing_transaction_id === params[0]).map((d) => ({")
L("        batch_id: d.batch_id, medicine_id: d.medicine_id, quantity_deducted: d.quantity, unit_price: d.unit_price,")
L("      }));")
L("      return { rows };")
L("    }")
L("    // FEFO batch lock SELECT")
L("    if (s.includes('FOR UPDATE SKIP LOCKED')) {")
L("      const eligible = batches")
L("        .filter((b) => b.phc_id === params[0] && b.medicine_id === params[1] && b.remaining_qty > 0)")
L("        .sort((a, b2) => a.expiry_date.localeCompare(b2.expiry_date));")
L("      return { rows: eligible.map((b) => ({ id: b.id, remaining_qty: b.remaining_qty, expiry_date: b.expiry_date, minimum_threshold: b.minimum_threshold })) };")
L("    }")
L("    // INSERT billing_transactions")
L("    if (s.includes('INSERT INTO billing_transactions')) {")
L("      const id = uid();")
L("      billingTxns.push({ id, phc_id: params[0], client_txn_id: params[1], patient_ref: params[2], dispensed_by_staff_id: params[3], total_amount: params[4], client_timestamp: params[5], status: 'completed' });")
L("      return { rows: [{ id }] };")
L("    }")
L("    // UPDATE inventory_batches")
L("    if (s.includes('UPDATE inventory_batches')) {")
L("      const batch = batches.find((b) => b.id === params[1]);")
L("      if (batch) batch.remaining_qty -= params[0];")
L("      return { rows: [] };")
L("    }")
L("    // INSERT dispensed_items")
L("    if (s.includes('INSERT INTO dispensed_items')) {")
L("      dispensedItems.push({ id: uid(), billing_transaction_id: params[0], batch_id: params[1], medicine_id: params[2], quantity: params[3], unit_price: params[4] });")
L("      return { rows: [] };")
L("    }")
L("    // INSERT consumption_velocity")
L("    if (s.includes('INSERT INTO consumption_velocity')) {")
L("      consumptionRows.push({ medicine_id: params[2], qty_dispensed: params[3] });")
L("      return { rows: [] };")
L("    }")
L("    // Threshold re-check SELECT (all batches for a medicine)")
L("    if (s.includes('FROM inventory_batches') && s.includes('medicine_id = $2')) {")
L("      return { rows: batches.filter((b) => b.phc_id === params[0] && b.medicine_id === params[1]) };")
L("    }")
L("    if (s.includes('set_config') || /^(BEGIN|COMMIT|ROLLBACK)$/.test(s)) return { rows: [] };")
L("    return { rows: [] };")
L("  };")
L("  return { query: handler, release: () => {} } as unknown as PoolClient;")
L("}")
